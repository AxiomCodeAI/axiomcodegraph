#!/usr/bin/env node
// Generate the scale/ fixtures (deterministic; re-run after editing, then --draft and review the counts).
//   routes-2k : 20 modules x 100 routes, each module a sub-app mounted under its own prefix
//   deep-mount: a chain of 10 sub-apps, each mounted inside the previous one
//   mw-200    : 200 app-level middleware registered before 10 routes (2,000 applications)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const C = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'cases', 'scale');
const w = (rel, txt) => { const f = path.join(C, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, txt); };
const VERBS = ['get', 'post', 'put', 'delete', 'patch'];

// routes-2k
let idx = `// census: route_mount_literal, verb_literal_path (scale: 2,000 routes; generated by tools/gen-scale.mjs)\nimport { Hono } from 'hono'\n`;
for (let m = 0; m < 20; m++) {
  let s = `import { Hono } from 'hono'\n\nexport const r${m} = new Hono()\n`;
  for (let i = 0; i < 100; i++) s += `r${m}.${VERBS[i % 5]}('/res${i}/:id', (c) => c.text('m${m} r${i}'))\n`;
  w(`routes-2k/src/mod${m}.ts`, s);
  idx += `import { r${m} } from './mod${m}'\n`;
}
idx += `\nconst app = new Hono()\n`;
for (let m = 0; m < 20; m++) idx += `app.route('/m${m}', r${m})\n`;
w('routes-2k/src/index.ts', idx + `\nexport default app\n`);
w('routes-2k/budget', '300\nrss_mb 2048\n'); // seconds, then peak RSS of the solve in MB

// deep-mount
let d = `// census: route_mount_literal (scale: 10-deep mounting; generated by tools/gen-scale.mjs)\nimport { Hono } from 'hono'\n\n`;
for (let i = 0; i < 10; i++) d += `const l${i} = new Hono()\nl${i}.get('/here', (c) => c.text('level ${i}'))\n`;
for (let i = 8; i >= 0; i--) d += `l${i}.route('/d${i + 1}', l${i + 1})\n`;
w('deep-mount/src/index.ts', d + `\nexport default l0\n`);
w('deep-mount/budget', '120\nrss_mb 2048\n'); // seconds, then peak RSS of the solve in MB

// mw-200
let mw = `// census: use_global, await_next (scale: 200 middleware x 10 routes; generated by tools/gen-scale.mjs)\nimport { Hono } from 'hono'\nimport type { MiddlewareHandler } from 'hono'\n\nconst app = new Hono()\n`;
for (let i = 0; i < 200; i++) mw += `const m${i}: MiddlewareHandler = async (c, next) => { await next() }\napp.use(m${i})\n`;
for (let i = 0; i < 10; i++) mw += `app.get('/r${i}', (c) => c.text('${i}'))\n`;
w('mw-200/src/index.ts', mw + `\nexport default app\n`);
w('mw-200/budget', '300\nrss_mb 2048\n'); // seconds, then peak RSS of the solve in MB
